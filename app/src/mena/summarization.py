class OllamaSummarizationProvider:
    """Local Ollama adapter for structured meeting summarization."""

    def __init__(
        self,
        *,
        model: str = OLLAMA_DEFAULT_MODEL,
        endpoint: str = OLLAMA_DEFAULT_ENDPOINT,
        timeout_seconds: float = 60.0,
    ) -> None:
        self.metadata = SummarizationProviderMetadata(
            name="ollama",
            model=model,
            endpoint=_summarization_local_ollama_endpoint(endpoint),
            num_ctx=OLLAMA_SUMMARIZATION_NUM_CTX,
            temperature=OLLAMA_SUMMARIZATION_TEMPERATURE,
            seed=OLLAMA_SUMMARIZATION_SEED,
        )
        self.timeout_seconds = timeout_seconds
        self._runtime_resource_used = False

    @property
    def runtime_resource_used(self) -> bool:
        return self._runtime_resource_used

    def summarize(self, request: SummarizationRequest) -> SummaryResult:
        records: list[ProductRequestRecord] = []
        timeline_payload = self._run_product(
            product="timeline",
            schema=TIMELINE_RESPONSE_SCHEMA,
            request=request,
            records=records,
        )
        action_payload = self._run_product(
            product="action_items",
            schema=ACTION_ITEMS_RESPONSE_SCHEMA,
            request=request,
            records=records,
        )
        summary_payload = self._run_product(
            product="general_summary",
            schema=GENERAL_SUMMARY_RESPONSE_SCHEMA,
            request=request,
            records=records,
        )
        combined = {
            "timeline": timeline_payload.get("timeline"),
            "action_items": action_payload.get("action_items"),
            "general_summary": summary_payload.get("general_summary"),
            "request_records": [record.to_dict() for record in records],
        }
        result = SummaryResult.from_dict(combined)
        _assert_output_language(result, request.policy.language)
        return result

    def _run_product(
        self,
        *,
        product: str,
        schema: Mapping[str, object],
        request: SummarizationRequest,
        records: list[ProductRequestRecord],
    ) -> Mapping[str, object]:
        system_content = _product_system_prompt(product, request.policy.language)
        user_content = _product_user_prompt(request)
        _guard_token_budget(
            product=product,
            system_content=system_content,
            user_content=user_content,
            num_ctx=OLLAMA_SUMMARIZATION_NUM_CTX,
        )
        payload = {
            "model": self.metadata.model,
            "stream": False,
            "format": schema,
            "options": OLLAMA_DETERMINISTIC_OPTIONS,
            "messages": [
                {"role": "system", "content": system_content},
                {"role": "user", "content": user_content},
            ],
        }
        response = self._post_json("/api/chat", payload)
        content = _summarization_ollama_message_content(response)
        _assert_ollama_response_not_truncated(
            product=product,
            response=response,
            content=content,
        )
        try:
            decoded = json.loads(strip_json_fence(content))
        except json.JSONDecodeError as exc:
            raise SummarizationContractError(
                _with_raw_ollama_message_content(
                    f"Ollama {product} response was not valid JSON.",
                    content,
                )
            ) from exc
        payload_mapping = _mapping(decoded, f"Ollama {product} response")
        try:
            _validate_product_payload(product, payload_mapping)
        except SummarizationContractError as exc:
            raise SummarizationContractError(
                _with_raw_ollama_message_content(str(exc), content)
            ) from exc
        prompt_eval_count, eval_count = _summarization_ollama_token_counts(
            product=product,
            response=response,
        )
        records.append(
            ProductRequestRecord(
                product=product,
                model=self.metadata.model,
                num_ctx=OLLAMA_SUMMARIZATION_NUM_CTX,
                temperature=OLLAMA_SUMMARIZATION_TEMPERATURE,
                seed=OLLAMA_SUMMARIZATION_SEED,
                prompt_eval_count=prompt_eval_count,
                eval_count=eval_count,
            )
        )
        return payload_mapping

    def _post_json(self, path: str, payload: Mapping[str, object]) -> Mapping[str, object]:
        try:
            if path == "/api/chat":
                self._runtime_resource_used = True
            return post_ollama_json(
                endpoint=str(self.metadata.endpoint),
                path=path,
                payload=payload,
                timeout_seconds=self.timeout_seconds,
            )
        except LocalLLMProviderUnavailable as exc:
            raise SummarizationProviderUnavailable(
                "Ollama summarization provider is unavailable."
            ) from exc
        except LocalLLMContractError as exc:
            raise SummarizationContractError(str(exc)) from exc

    def release_runtime_resource(self, lease: RuntimeLease) -> RuntimeReleaseResult:
        """Release this provider's local Ollama model residency."""

        try:
            done_reason = unload_ollama_model(
                endpoint=str(self.metadata.endpoint),
                model=self.metadata.model,
                timeout_seconds=self.timeout_seconds,
            )
        except LocalLLMProviderUnavailable as exc:
            raise SummarizationProviderUnavailable(
                "Ollama summarization provider is unavailable during release."
            ) from exc
        except LocalLLMContractError as exc:
            raise SummarizationContractError(str(exc)) from exc
        return RuntimeReleaseResult(
            lease=lease,
            status="released",
            detail=f"Ollama model release completed: {done_reason}.",
        )


@dataclass(frozen=True)
class SummaryArtifact:
    """Persisted `summary.v2` three-product note-package artifact."""

    version: int
    session_id: str
    merged_transcript_artifact: ArtifactRef
    manual_notes_artifact: ArtifactRef | None
    policy: Mapping[str, object]
    provider: SummarizationProviderMetadata
    timeline: tuple[str, ...]
    action_items: tuple[SummaryActionItem, ...]
    general_summary: str
    created_at: str
    request_records: tuple[ProductRequestRecord, ...] = ()

    @classmethod
    def from_dict(cls, data: object) -> Self:
        item = _mapping(data, "Summary artifact")
        artifact = cls(
            version=_required_int(item, "version", "Summary artifact"),
            session_id=_required_str(item, "session_id", "Summary artifact"),
            merged_transcript_artifact=ArtifactRef.from_dict(
                item.get("merged_transcript_artifact")
            ),
            manual_notes_artifact=(
                None
                if item.get("manual_notes_artifact") is None
                else ArtifactRef.from_dict(item.get("manual_notes_artifact"))
            ),
            policy=_summary_policy_payload(item.get("policy")),
            provider=_provider_from_dict(item.get("provider")),
            timeline=tuple(_str_list(item, "timeline", "Summary timeline")),
            action_items=tuple(
                SummaryActionItem.from_dict(action) for action in _list(item, "action_items")
            ),
            general_summary=_required_str(item, "general_summary", "Summary artifact"),
            created_at=_required_str(item, "created_at", "Summary artifact"),
            request_records=_request_records(item, required=True),
        )
        if artifact.version != SUMMARY_SCHEMA_VERSION:
            raise SummarizationContractError("Unsupported summary artifact version.")
        if not artifact.timeline:
            raise SummarizationContractError("Summary artifact timeline must not be empty.")
        return artifact

    def to_dict(self) -> dict[str, object]:
        return {
            "version": self.version,
            "session_id": self.session_id,
            "merged_transcript_artifact": self.merged_transcript_artifact.to_dict(),
            "manual_notes_artifact": (
                None if self.manual_notes_artifact is None else self.manual_notes_artifact.to_dict()
            ),
            "policy": dict(self.policy),
            "provider": self.provider.to_dict(),
            "timeline": list(self.timeline),
            "action_items": [action.to_dict() for action in self.action_items],
            "general_summary": self.general_summary,
            "created_at": self.created_at,
            "request_records": [record.to_dict() for record in self.request_records],
        }

    def to_json_bytes(self) -> bytes:
        return (json.dumps(self.to_dict(), indent=2, sort_keys=True) + "\n").encode("utf-8")


@dataclass(frozen=True)
class SummarizationStageResult:
    """Result of running or reusing the summarization stage."""

    state: ProcessingStageState
    summary: SummaryArtifact
    summary_record: ArtifactRecord
    skipped: bool = False
    skip_reason: str | None = None


def persist_summary_artifact(
    *,
    store: ArtifactStore,
    artifact: SummaryArtifact,
    name: str | Path,
    correction_overlay_record: ArtifactRecord | None = None,
) -> ArtifactRecord:
    """Persist one summary payload through the artifact store contract."""

    SummaryArtifact.from_dict(artifact.to_dict())
    metadata: dict[str, object] = {
        "category": "summary",
        "contract": "summary.v2",
        "policy_config_id": _policy_config_id(artifact.policy),
        "provider_config_id": artifact.provider.config_id,
        "stage_config_id": _stage_config_id(
            policy_config_id=_policy_config_id(artifact.policy),
            provider_config_id=artifact.provider.config_id,
        ),
        "summary_created_at": artifact.created_at,
        "merged_transcript_artifact_id": artifact.merged_transcript_artifact.id,
        "manual_notes_artifact_id": (
            None if artifact.manual_notes_artifact is None else artifact.manual_notes_artifact.id
        ),
    }
    if correction_overlay_record is not None:
        metadata["correction_overlay_artifact_id"] = correction_overlay_record.id
    return store.store(
        artifact_type=SUMMARY_ARTIFACT_TYPE,
        name=name,
        data=artifact.to_json_bytes(),
        version=SUMMARY_ARTIFACT_VERSION,
        metadata=metadata,
    )


def run_summarization_stage(
    *,
    store: ArtifactStore,
    ledger: ProcessingStageLedger,
    merged_transcript_record: ArtifactRecord,
    provider: SummarizationProvider,
    correction_overlay_record: ArtifactRecord | None = None,
    policy: SummarizationPolicy | None = None,
    manual_notes_record: ArtifactRecord | None = None,
    stage: str = SUMMARIZATION_STAGE,
    attempt: int = 1,
    skip_completed: bool = True,
    now: datetime | None = None,
) -> SummarizationStageResult:
    """Generate a structured meeting summary from a merged transcript artifact."""

    effective_policy = policy or SummarizationPolicy()
    correction_overlay_used_record = correction_overlay_record
    manual_notes_used_record = (
        manual_notes_record if effective_policy.include_manual_notes else None
    )
    input_refs = [ArtifactRef.from_record(merged_transcript_record)]
    if correction_overlay_used_record is not None:
        input_refs.append(ArtifactRef.from_record(correction_overlay_used_record))
    if manual_notes_used_record is not None:
        input_refs.append(ArtifactRef.from_record(manual_notes_used_record))
    input_artifacts = tuple(input_refs)
    policy_payload = effective_policy.to_dict()
    policy_config_id = effective_policy.config_id
    stage_config_id = _stage_config_id(
        policy_config_id=policy_config_id,
        provider_config_id=provider.metadata.config_id,
    )

    if skip_completed:
        completed = _completed_state_for_inputs(
            store=store,
            ledger=ledger,
            stage=stage,
            input_artifacts=input_artifacts,
            policy_config_id=policy_config_id,
            provider_config_id=provider.metadata.config_id,
            stage_config_id=stage_config_id,
        )
        if completed is not None:
            reused = _load_reusable_output(store=store, completed=completed)
            if reused is not None:
                record, artifact = reused
                timestamp = _timestamp(now)
                state = ledger.record(
                    ProcessingStageState(
                        version=1,
                        session_id=ledger.session_id,
                        run_id=ledger.run_id,
                        stage=stage,
                        status="skipped",
                        input_artifacts=input_artifacts,
                        output_artifacts=completed.output_artifacts,
                        started_at=timestamp,
                        completed_at=timestamp,
                        error=None,
                        attempt=attempt,
                    )
                )
                return SummarizationStageResult(
                    state=state,
                    summary=artifact,
                    summary_record=record,
                    skipped=True,
                    skip_reason="completed_output_reused",
                )

    started = ledger.mark_running(
        stage=stage,
        input_artifacts=input_artifacts,
        attempt=attempt,
        now=now,
    )
    try:
        merged_transcript = _verify_and_load_merged_transcript(
            store=store, record=merged_transcript_record
        )
        if merged_transcript.session_id != ledger.session_id:
            raise SummarizationContractError(
                "Merged transcript session_id must match the processing ledger."
            )

        transcript_for_summary = merged_transcript
        if correction_overlay_used_record is not None:
            overlay = _verify_and_load_correction_overlay(
                store=store, record=correction_overlay_used_record
            )
            transcript_for_summary = apply_correction_overlay(
                source_transcript=merged_transcript,
                source_transcript_record=merged_transcript_record,
                overlay=overlay,
            )

        manual_notes = None
        if manual_notes_used_record is not None:
            manual_notes = _verify_and_load_manual_notes(
                store=store, record=manual_notes_used_record
            )
        result = provider.summarize(
            SummarizationRequest(
                session_id=merged_transcript.session_id,
                merged_transcript=transcript_for_summary,
                manual_notes=manual_notes,
                policy=effective_policy,
            )
        )
        artifact = SummaryArtifact(
            version=SUMMARY_SCHEMA_VERSION,
            session_id=merged_transcript.session_id,
            merged_transcript_artifact=ArtifactRef.from_record(merged_transcript_record),
            manual_notes_artifact=(
                None
                if manual_notes_used_record is None
                else ArtifactRef.from_record(manual_notes_used_record)
            ),
            policy=policy_payload,
            provider=provider.metadata,
            timeline=result.timeline,
            action_items=result.action_items,
            general_summary=result.general_summary,
            created_at=_timestamp(now),
            request_records=result.request_records,
        )
        output_record = persist_summary_artifact(
            store=store,
            artifact=artifact,
            correction_overlay_record=correction_overlay_used_record,
            name=_summary_artifact_name(
                run_id=ledger.run_id,
                merged_transcript_sha256=merged_transcript_record.sha256,
                stage_config_id=stage_config_id,
                manual_notes_sha256=(
                    None if manual_notes_used_record is None else manual_notes_used_record.sha256
                ),
                correction_overlay_sha256=(
                    None
                    if correction_overlay_used_record is None
                    else correction_overlay_used_record.sha256
                ),
                correction_overlay_artifact_id=(
                    None
                    if correction_overlay_used_record is None
                    else correction_overlay_used_record.id
                ),
                attempt=attempt,
            ),
        )
    except (
        SummarizationError,
        MergeTimingContractError,
        CorrectionOverlayContractError,
        json.JSONDecodeError,
        KeyError,
        FileExistsError,
        UnicodeDecodeError,
    ) as exc:
        failed = ledger.mark_failed(
            stage=stage,
            input_artifacts=input_artifacts,
            error=ProcessingErrorInfo(
                message=_processing_error_message(exc),
                retryable=isinstance(exc, SummarizationProviderUnavailable),
                code="summarization_failed",
            ),
            attempt=attempt,
            started_at=started.started_at,
            now=now,
        )
        message = failed.error.message if failed.error else str(exc)
        if isinstance(exc, SummarizationProviderUnavailable):
            raise SummarizationProviderUnavailable(message) from exc
        raise SummarizationError(message) from exc

    completed = ledger.mark_completed(
        stage=stage,
        input_artifacts=input_artifacts,
        output_artifacts=(ArtifactRef.from_record(output_record),),
        attempt=attempt,
        started_at=started.started_at,
        now=now,
    )
    return SummarizationStageResult(
        state=completed,
        summary=artifact,
        summary_record=output_record,
    )


def _verify_and_load_correction_overlay(
    *, store: ArtifactStore, record: ArtifactRecord
) -> CorrectionOverlayArtifact:
    if record.artifact_type != CORRECTION_OVERLAY_ARTIFACT_TYPE:
        raise SummarizationContractError(
            "Correction overlay artifact must have correction_overlay type."
        )
    if not store.verify(record.id).ok:
        raise SummarizationContractError("Correction overlay artifact failed verification.")
    return CorrectionOverlayArtifact.from_dict(json.loads(store.retrieve(record.id)))


def _verify_and_load_merged_transcript(
    *, store: ArtifactStore, record: ArtifactRecord
) -> MergedTranscriptArtifact:
    verification = store.verify(record.id)
    if not verification.ok:
        raise SummarizationContractError(
            verification.error or "merged transcript artifact failed verification"
        )
    return MergedTranscriptArtifact.from_dict(json.loads(store.retrieve(record.id)))


def _verify_and_load_manual_notes(*, store: ArtifactStore, record: ArtifactRecord) -> str:
    if record.artifact_type != MANUAL_NOTES_ARTIFACT_TYPE:
        raise SummarizationContractError("Manual notes artifact must have manual_notes type.")
    if record.metadata.get("contract") != MANUAL_NOTES_CONTRACT:
        raise SummarizationContractError("Manual notes artifact has unsupported contract.")
    if not store.verify(record.id).ok:
        raise SummarizationContractError("Manual notes artifact failed verification.")
    return store.retrieve(record.id).decode("utf-8")


def _completed_state_for_inputs(
    *,
    store: ArtifactStore,
    ledger: ProcessingStageLedger,
    stage: str,
    input_artifacts: tuple[ArtifactRef, ...],
    policy_config_id: str,
    provider_config_id: str,
    stage_config_id: str,
) -> ProcessingStageState | None:
    for state in reversed(ledger.states(stage=stage)):
        if (
            state.status != "completed"
            or state.input_artifacts != input_artifacts
            or len(state.output_artifacts) != 1
        ):
            continue
        output_ref = state.output_artifacts[0]
        if not _artifact_ref_verifies(store=store, artifact_ref=output_ref):
            continue
        record = _record_for_ref(store=store, artifact_ref=output_ref)
        if record.metadata.get("stage_config_id") == stage_config_id or (
            record.metadata.get("policy_config_id") == policy_config_id
            and record.metadata.get("provider_config_id") == provider_config_id
        ):
            return state
    return None


def _load_reusable_output(
    *, store: ArtifactStore, completed: ProcessingStageState
) -> tuple[ArtifactRecord, SummaryArtifact] | None:
    output_ref = completed.output_artifacts[0]
    try:
        record = _record_for_ref(store=store, artifact_ref=output_ref)
        artifact = SummaryArtifact.from_dict(json.loads(store.retrieve(record.id)))
    except (SummarizationError, json.JSONDecodeError, KeyError, UnicodeDecodeError):
        return None
    return record, artifact


def _record_for_ref(*, store: ArtifactStore, artifact_ref: ArtifactRef) -> ArtifactRecord:
    for record in store.list(artifact_type=artifact_ref.artifact_type):
        if (
            record.id == artifact_ref.id
            and record.version == artifact_ref.version
            and record.sha256 == artifact_ref.sha256
        ):
            return record
    raise SummarizationContractError("Summary output ref does not match a known artifact.")


def _artifact_ref_verifies(*, store: ArtifactStore, artifact_ref: ArtifactRef) -> bool:
    try:
        record = _record_for_ref(store=store, artifact_ref=artifact_ref)
        verification = store.verify(record.id)
    except (KeyError, SummarizationContractError):
        return False
    return verification.ok


def _summary_artifact_name(
    *,
    run_id: str,
    merged_transcript_sha256: str,
    stage_config_id: str,
    manual_notes_sha256: str | None,
    correction_overlay_sha256: str | None,
    correction_overlay_artifact_id: str | None,
    attempt: int,
) -> Path:
    notes_scope = manual_notes_sha256 or "no-manual-notes"
    overlay_scope = (
        f"{correction_overlay_artifact_id}:{correction_overlay_sha256}"
        if correction_overlay_artifact_id is not None
        else "no-correction-overlay"
    )
    scope = sha256(f"{stage_config_id}:{notes_scope}:{overlay_scope}".encode()).hexdigest()[:12]
    return Path(run_id) / merged_transcript_sha256[:12] / scope / f"summary-{attempt:03d}.json"


_PRODUCT_INSTRUCTIONS: dict[str, str] = {
    "timeline": (
        "Return only key timeline (array of strings). Each entry is a meaningful "
        "chronological event from the meeting, not a bare date."
    ),
    "action_items": (
        "Return only key action_items (array of objects with text, owner, due). "
        "Each item is an actual task, not a topic label; owner and due may be null."
    ),
    "general_summary": (
        "Return only key general_summary (string): a concise high-level overview of the meeting."
    ),
}


def _product_system_prompt(product: str, language: str) -> str:
    return (
        "You extract meeting notes into strict JSON. "
        f"{_PRODUCT_INSTRUCTIONS[product]} "
        "Be faithful to the transcript and manual notes. "
        f"Write every user-facing string in {language}."
    )


def _product_user_prompt(request: SummarizationRequest) -> str:
    return json.dumps(
        {
            "task": "meeting_notes",
            "language": request.policy.language,
            "output_language": _output_language_instruction(request.policy.language),
            "transcript": {
                "segments": [
                    {
                        "speaker": segment.speaker.label,
                        "start_seconds": segment.start_seconds,
                        "end_seconds": segment.end_seconds,
                        "text": segment.text,
                    }
                    for segment in request.merged_transcript.segments
                ],
            },
            "manual_notes": request.manual_notes,
        },
        ensure_ascii=False,
        sort_keys=True,
    )


def _output_language_instruction(language: str) -> str:
    return (
        f"Write all user-facing strings in {language}: timeline entries, "
        "action item text, generated owner/due wording, and the general summary."
    )


def _validate_product_payload(product: str, payload: Mapping[str, object]) -> None:
    if product == "timeline":
        if not _str_list(payload, "timeline", "Summary timeline"):
            raise SummarizationContractError("Summary timeline must not be empty.")
    elif product == "action_items":
        for action in _list(payload, "action_items"):
            SummaryActionItem.from_dict(action)
    else:
        _required_str(payload, "general_summary", "Summary result")


def _assert_output_language(result: SummaryResult, language: str) -> None:
    """Fail loudly when a non-English request produced English-drifted output."""

    if _is_english_language(language):
        return
    for label, text in _note_package_user_facing_fields(result):
        if _looks_like_english_drift(text):
            raise SummarizationContractError(
                f"Note-package {label} output drifted to English but '{language}' "
                "was requested; refusing to persist off-language notes "
                "(small local models drift to English)."
            )


def _is_english_language(language: str) -> bool:
    return language.replace("_", "-").split("-", 1)[0].lower() == "en"


def _note_package_user_facing_fields(result: SummaryResult) -> tuple[tuple[str, str], ...]:
    parts: list[tuple[str, str]] = [
        (f"timeline[{index}]", entry) for index, entry in enumerate(result.timeline)
    ]
    for index, action in enumerate(result.action_items):
        parts.append((f"action_items[{index}].text", action.text))
        if action.owner:
            parts.append((f"action_items[{index}].owner", action.owner))
        if action.due:
            parts.append((f"action_items[{index}].due", action.due))
    parts.append(("general_summary", result.general_summary))
    return tuple(parts)


def _looks_like_english_drift(text: str) -> bool:
    tokens = re.findall(r"[^\W\d_]+", text.lower())
    if len(tokens) < _ENGLISH_DRIFT_MIN_TOKENS:
        return False
    hits = [token for token in tokens if token in _ENGLISH_DRIFT_STOPWORDS]
    if len(set(hits)) < _ENGLISH_DRIFT_MIN_DISTINCT:
        return False
    return len(hits) / len(tokens) >= _ENGLISH_DRIFT_MIN_RATIO


def _estimate_prompt_tokens(text: str) -> int:
    # Ollama does not expose a preflight tokenizer here. Counting UTF-8 bytes is
    # a hard upper bound for byte-fallback tokenizers and avoids len(text)/4
    # undercounts for short words, IDs, and punctuation-heavy notes.
    return len(text.encode("utf-8"))


def _guard_token_budget(
    *,
    product: str,
    system_content: str,
    user_content: str,
    num_ctx: int,
) -> None:
    estimate = _estimate_prompt_tokens(system_content) + _estimate_prompt_tokens(user_content)
    budget = int(num_ctx * TOKEN_BUDGET_FRACTION)
    if estimate > budget:
        raise SummarizationTokenBudgetError(
            f"Estimated {product} prompt tokens ({estimate}) exceed the configured "
            f"num_ctx budget ({budget} of {num_ctx}); refusing to send to avoid "
            "silent context truncation."
        )


def _summarization_ollama_token_counts(
    *,
    product: str,
    response: Mapping[str, object],
) -> tuple[int, int]:
    try:
        prompt_eval_count, eval_count = ollama_token_counts(response)
    except LocalLLMContractError as exc:
        raise SummarizationContractError(str(exc)) from exc
    missing = [
        name
        for name, value in (
            ("prompt_eval_count", prompt_eval_count),
            ("eval_count", eval_count),
        )
        if value is None
    ]
    if missing:
        raise SummarizationContractError(
            f"Ollama {product} response omitted required token counts: {', '.join(missing)}."
        )
    assert prompt_eval_count is not None
    assert eval_count is not None
    return prompt_eval_count, eval_count


def _assert_ollama_response_not_truncated(
    *,
    product: str,
    response: Mapping[str, object],
    content: str,
) -> None:
    if response.get("done_reason") == "length":
        raise SummarizationContractError(
            _with_raw_ollama_message_content(
                f"Ollama {product} response was truncated by the generation token limit "
                "(done_reason=length).",
                content,
            )
        )


def _summarization_ollama_message_content(response: Mapping[str, object]) -> str:
    try:
        return ollama_message_content(response)
    except LocalLLMContractError as exc:
        raise SummarizationContractError(str(exc)) from exc


def _summarization_local_ollama_endpoint(endpoint: str) -> str:
    try:
        return local_ollama_endpoint(endpoint)
    except (LocalLLMContractError, ValueError) as exc:
        raise SummarizationContractError(str(exc)) from exc


def _with_raw_ollama_message_content(message: str, content: str) -> str:
    return f"{message} Raw Ollama message content: {_diagnostic_excerpt(content)}"


def _processing_error_message(exc: BaseException) -> str:
    message = str(exc)
    if isinstance(exc, SummarizationContractError):
        message = message.split(" Raw Ollama message content:", 1)[0]
    return message


def _diagnostic_excerpt(content: str, *, limit: int = 1000) -> str:
    stripped = content.strip()
    if len(stripped) <= limit:
        return stripped
    return f"{stripped[:limit]}... [truncated]"


def _provider_from_dict(data: object) -> SummarizationProviderMetadata:
    item = _mapping(data, "Summary provider")
    provider = SummarizationProviderMetadata(
        name=_required_str(item, "name", "Summary provider"),
        model=_required_str(item, "model", "Summary provider"),
        endpoint=_optional_str(item, "endpoint", "Summary provider"),
        prompt_policy=_required_str(item, "prompt_policy", "Summary provider"),
    )
    if provider.prompt_policy not in SUPPORTED_PROMPT_POLICIES:
        raise SummarizationContractError("Unsupported summary provider prompt policy.")
    return provider


def _summary_policy_payload(data: object) -> dict[str, object]:
    policy = _mapping(data, "Summary policy")
    required = {
        "policy_version",
        "prompt_policy",
        "language",
        "include_manual_notes",
    }
    if set(policy) != required:
        raise SummarizationContractError("Summary policy has unsupported fields.")
    SummarizationPolicy.from_dict(policy)
    return dict(policy)


def _policy_config_id(policy: Mapping[str, object]) -> str:
    return json.dumps(dict(policy), sort_keys=True, separators=(",", ":"))


def _stage_config_id(*, policy_config_id: str, provider_config_id: str) -> str:
    return json.dumps(
        {
            "policy_config_id": policy_config_id,
            "provider_config_id": provider_config_id,
        },
        sort_keys=True,
        separators=(",", ":"),
    )


def _mapping(data: object, label: str) -> Mapping[str, object]:
    if not isinstance(data, Mapping):
        raise SummarizationContractError(f"{label} must be a JSON object.")
    return data


def _list(data: Mapping[str, object], field_name: str) -> list[object]:
    value = data.get(field_name)
    if not isinstance(value, list):
        raise SummarizationContractError(f"Field '{field_name}' must be an array.")
    return value


def _str_list(data: Mapping[str, object], field_name: str, label: str) -> list[str]:
    values = _list(data, field_name)
    if any(not isinstance(value, str) or not value for value in values):
        raise SummarizationContractError(f"{label} must contain non-empty strings.")
    return [str(value) for value in values]


def _required_str(data: Mapping[str, object], field_name: str, label: str) -> str:
    return required_str(
        data,
        field_name,
        error=SummarizationContractError,
        message=f"Field '{field_name}' in {label} must be a non-empty string.",
    )


def _optional_str(data: Mapping[str, object], field_name: str, label: str) -> str | None:
    return optional_str(
        data,
        field_name,
        error=SummarizationContractError,
        message=f"Field '{field_name}' in {label} must be null or a non-empty string.",
    )


def _required_int(data: Mapping[str, object], field_name: str, label: str) -> int:
    return required_int(
        data,
        field_name,
        error=SummarizationContractError,
        message=f"Field '{field_name}' in {label} must be an integer.",
    )


def _required_bool(data: Mapping[str, object], field_name: str, label: str) -> bool:
    return required_bool(
        data,
        field_name,
        error=SummarizationContractError,
        message=f"Field '{field_name}' in {label} must be a boolean.",
    )


def _required_number(data: Mapping[str, object], field_name: str, label: str) -> float:
    value = data.get(field_name)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise SummarizationContractError(f"Field '{field_name}' in {label} must be a number.")
    return value


def _optional_int(data: Mapping[str, object], field_name: str, label: str) -> int | None:
    value = data.get(field_name)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int):
        raise SummarizationContractError(
            f"Field '{field_name}' in {label} must be null or an integer."
        )
    return value


def _required_positive_int(data: Mapping[str, object], field_name: str, label: str) -> int:
    value = _required_int(data, field_name, label)
    if value < 1:
        raise SummarizationContractError(f"Field '{field_name}' in {label} must be at least 1.")
    return value


def _optional_nonnegative_int(
    data: Mapping[str, object], field_name: str, label: str
) -> int | None:
    value = _optional_int(data, field_name, label)
    if value is not None and value < 0:
        raise SummarizationContractError(f"Field '{field_name}' in {label} must be at least 0.")
    return value


def _request_records(
    data: Mapping[str, object], *, required: bool = False
) -> tuple[ProductRequestRecord, ...]:
    value = data.get("request_records")
    if value is None:
        if required:
            raise SummarizationContractError(
                "Field 'request_records' is required for version 2 summary artifacts."
            )
        return ()
    if not isinstance(value, list):
        raise SummarizationContractError("Field 'request_records' must be an array.")
    records = tuple(ProductRequestRecord.from_dict(record) for record in value)
    if required:
        products = tuple(record.product for record in records)
        expected = set(REQUIRED_NOTE_PRODUCTS)
        actual = set(products)
        if len(records) != len(REQUIRED_NOTE_PRODUCTS) or actual != expected:
            raise SummarizationContractError(
                "Field 'request_records' must contain exactly one record for each "
                "note product: timeline, action_items, general_summary."
            )
        if len(actual) != len(products):
            raise SummarizationContractError(
                "Field 'request_records' must not contain duplicate note products."
            )
    return records


def _timestamp(now: datetime | None) -> str:
    return utc_timestamp(now or datetime.now(UTC))
